package main

import (
	"crypto/sha256"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const checksumFilename = "upstream-files.sha256"

// Keep this list limited to files that remain byte-for-byte identical to
// upstream. Microsoft-specific code lives in ms_*.go, and go-dl omits gotip.go.
var upstreamFiles = []string{
	"signal_notunix.go",
	"signal_unix.go",
	"version.go",
	"version_test.go",
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	repository := flag.String("repo", "https://github.com/golang/dl.git", "Upstream Git repository")
	branch := flag.String("branch", "master", "Upstream Git branch")
	flag.Parse()

	if _, err := os.Stat(filepath.Join("cmd", "fetch-upstream", "main.go")); err != nil {
		return fmt.Errorf("expected to run from the internal/gen module: %w", err)
	}
	versionDir := filepath.Join("..", "..", "internal", "version")

	tempDir, err := os.MkdirTemp("", "go-dl-fetch-upstream-*")
	if err != nil {
		return fmt.Errorf("create temporary clone directory: %w", err)
	}
	defer os.RemoveAll(tempDir)

	clone := exec.Command("git", "clone", "--depth", "1", "--branch", *branch, *repository, tempDir)
	if output, err := clone.CombinedOutput(); err != nil {
		return fmt.Errorf("clone upstream repository: %w\n%s", err, output)
	}

	commitOutput, err := exec.Command("git", "-C", tempDir, "rev-parse", "HEAD").Output()
	if err != nil {
		return fmt.Errorf("read upstream commit: %w", err)
	}
	commit := strings.TrimSpace(string(commitOutput))

	files := append([]string(nil), upstreamFiles...)
	sort.Strings(files)
	var checksums strings.Builder
	fmt.Fprintf(&checksums, "# Generated by internal/gen/cmd/fetch-upstream\n")
	fmt.Fprintf(&checksums, "# Upstream commit: %s\n", commit)
	for _, name := range files {
		source := "HEAD:internal/version/" + name
		// Read the Git blob rather than the clone worktree so core.autocrlf
		// cannot change the bytes copied or recorded in the checksum file.
		data, err := exec.Command("git", "-C", tempDir, "show", source).Output()
		if err != nil {
			return fmt.Errorf("read upstream file %q from Git: %w", name, err)
		}
		if err := os.WriteFile(filepath.Join(versionDir, name), data, 0o644); err != nil {
			return fmt.Errorf("write upstream file %q: %w", name, err)
		}
		fmt.Fprintf(&checksums, "%x  %s\n", sha256.Sum256(data), name)
	}
	if err := os.WriteFile(filepath.Join(versionDir, checksumFilename), []byte(checksums.String()), 0o644); err != nil {
		return fmt.Errorf("write upstream checksums: %w", err)
	}

	fmt.Printf("Updated internal/version from %s at %s\n", *repository, commit)
	return nil
}
